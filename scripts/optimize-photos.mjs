// Optimizes the original gallery photos for the web.
//
//   photos-originals/<name>.<ext>  →  src/assets/gallery/<slug>.webp        (max 1600px wide)
//                                     src/assets/gallery/<slug>-thumb.webp  (max 600px wide)
//                                     src/assets/gallery/manifest.ts        (dimensions per photo)
//
// All metadata (EXIF, GPS, XMP, IPTC, ICC) is stripped: sharp drops it unless
// told otherwise. `.rotate()` bakes the EXIF orientation into the pixels first,
// so photos taken in portrait do not come out sideways.
//
// Usage: npm run photos

import { mkdir, readdir, rm, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const inputDir = path.join(root, 'photos-originals')
const outputDir = path.join(root, 'src/assets/gallery')

const FULL_WIDTH = 1600
const THUMB_WIDTH = 600
const QUALITY = 80
const INPUT_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif', '.tif', '.tiff', '.heic', '.heif'])

/** Stable, URL-safe name derived from the original file name. */
function slugify(fileName) {
  return path
    .parse(fileName)
    .name.normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function formatBytes(bytes) {
  return `${(bytes / 1024 / 1024).toFixed(2)} MB`
}

async function optimize(inputPath, outputPath, width) {
  return sharp(inputPath)
    .rotate()
    .resize({ width, withoutEnlargement: true })
    .webp({ quality: QUALITY })
    .toFile(outputPath)
}

async function main() {
  const files = (await readdir(inputDir).catch(() => []))
    .filter((file) => INPUT_EXTENSIONS.has(path.extname(file).toLowerCase()))
    .sort((a, b) => a.localeCompare(b, 'es', { numeric: true }))

  if (files.length === 0) {
    console.error(`No photos found in ${path.relative(root, inputDir)}/`)
    process.exit(1)
  }

  const slugs = new Map()
  for (const file of files) {
    const slug = slugify(file)
    if (!slug) throw new Error(`Cannot derive a file name from "${file}"`)
    if (slugs.has(slug)) throw new Error(`"${file}" and "${slugs.get(slug)}" both map to "${slug}"`)
    slugs.set(slug, file)
  }

  // Start clean so the output always mirrors photos-originals/ exactly.
  await rm(outputDir, { recursive: true, force: true })
  await mkdir(outputDir, { recursive: true })

  const manifest = {}
  let originalTotal = 0
  let fullTotal = 0
  let thumbTotal = 0

  for (const [slug, file] of slugs) {
    const inputPath = path.join(inputDir, file)
    const [{ size: originalSize }, full, thumb] = await Promise.all([
      stat(inputPath),
      optimize(inputPath, path.join(outputDir, `${slug}.webp`), FULL_WIDTH),
      optimize(inputPath, path.join(outputDir, `${slug}-thumb.webp`), THUMB_WIDTH),
    ])

    originalTotal += originalSize
    fullTotal += full.size
    thumbTotal += thumb.size
    manifest[slug] = {
      width: full.width,
      height: full.height,
      thumbWidth: thumb.width,
      thumbHeight: thumb.height,
    }
    console.log(`✓ ${file} → ${slug}.webp (${full.width}×${full.height}), ${slug}-thumb.webp (${thumb.width}×${thumb.height})`)
  }

  const manifestSource = `// Generated by scripts/optimize-photos.mjs — do not edit by hand. Run \`npm run photos\`.

export interface GalleryPhotoSize {
  width: number
  height: number
  thumbWidth: number
  thumbHeight: number
}

export const galleryManifest: Record<string, GalleryPhotoSize> = ${JSON.stringify(manifest, null, 2)}
`
  await writeFile(path.join(outputDir, 'manifest.ts'), manifestSource)

  const optimizedTotal = fullTotal + thumbTotal
  console.log(`
${files.length} photos processed
  Originals:        ${formatBytes(originalTotal)}
  Optimized full:   ${formatBytes(fullTotal)}
  Optimized thumbs: ${formatBytes(thumbTotal)}
  Optimized total:  ${formatBytes(optimizedTotal)} (${Math.round((1 - optimizedTotal / originalTotal) * 100)}% smaller)`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
